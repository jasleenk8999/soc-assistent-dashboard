function isValidApiKey(key: string | undefined): boolean {
  if (!key) return false;
  const trimmed = key.trim();
  if (!trimmed) return false;
  if (
    trimmed.startsWith("your_") ||
    trimmed.includes("api_key_here") ||
    trimmed === "placeholder" ||
    trimmed === "sk-xxx"
  ) {
    return false;
  }
  return true;
}

export async function generateExplanation(
  alert: AlertContext,
  logs: LogContext[]
): Promise<ExplanationResult> {
  const provider = (process.env.AI_PROVIDER || "").toLowerCase().trim();
  const rawApiKey = process.env.AI_API_KEY || process.env.OPENAI_API_KEY || "";
  const apiKey = isValidApiKey(rawApiKey) ? rawApiKey.trim() : "";
  const model =
    process.env.AI_MODEL ||
    (provider === "openai" ? "gpt-4o-mini" : provider === "google" ? "gemini-1.5-flash" : "");

  // No provider or key: return deterministic fallback
  if (!apiKey || provider === "fallback" || (!provider && !apiKey)) {
    return {
      sections: buildDeterministicFallback(alert, logs),
      provider: "fallback",
      model: null,
      status: "completed",
    };
  }

  // Determine effective provider
  const effectiveProvider = provider || (apiKey ? "openai" : "fallback");

  if (effectiveProvider === "fallback") {
    return {
      sections: buildDeterministicFallback(alert, logs),
      provider: "fallback",
      model: null,
      status: "completed",
    };
  }

  const prompt = buildPrompt(alert, logs);

  try {
    let rawText = "";

    if (effectiveProvider === "openai") {
      rawText = await callOpenAI(prompt, model || "gpt-4o-mini", apiKey);
    } else if (effectiveProvider === "google") {
      rawText = await callGoogleAI(prompt, model || "gemini-1.5-flash", apiKey);
    } else {
      throw new Error(`Unsupported AI_PROVIDER: "${effectiveProvider}". Use "openai" or "google".`);
    }

    const sections = parseSections(rawText);

    if (!validateSections(sections)) {
      console.warn("[IncidentExplanationService] AI response parse validation failed — using deterministic fallback.");
      return {
        sections: buildDeterministicFallback(alert, logs),
        provider: "fallback",
        model: null,
        status: "completed",
        errorMessage: "AI output did not meet minimum section quality threshold; deterministic fallback used.",
      };
    }

    return {
      sections,
      provider: effectiveProvider,
      model: model || null,
      status: "completed",
    };
  } catch (err: any) {
    const errMsg = err?.name === "AbortError"
      ? `AI request timed out after ${AI_REQUEST_TIMEOUT_MS}ms`
      : err?.message || "Unknown AI provider error";

    console.error("[IncidentExplanationService] AI call failed, falling back to deterministic explanation:", errMsg);

    // Always provide the high-quality deterministic fallback so analyst work is unblocked
    return {
      sections: buildDeterministicFallback(alert, logs),
      provider: "fallback",
      model: null,
      status: "completed",
      errorMessage: `AI provider error: ${errMsg}. Gracefully fallen back to rule-grounded explanation.`,
    };
  }
}
