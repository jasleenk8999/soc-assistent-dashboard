// Response Parsing
// ---------------------------------------------------------------------------

function parseSections(raw: string): ExplanationSections {
  const extract = (label: string): string => {
    const re = new RegExp(`${label}:\\s*([\\s\\S]*?)(?=\\n[A-Z_]+:|$)`, "i");
    const m = raw.match(re);
    return m ? m[1].trim() : "Not available in this explanation.";
  };

  return {
    executiveSummary: extract("EXECUTIVE_SUMMARY"),
    whyItTriggered: extract("WHY_IT_TRIGGERED"),
    evidenceNarrative: extract("EVIDENCE_NARRATIVE"),
    mitreContext: extract("MITRE_CONTEXT"),
    potentialImpact: extract("POTENTIAL_IMPACT"),
    confidenceAndUncertainty: extract("CONFIDENCE_AND_UNCERTAINTY"),
    investigationSteps: extract("INVESTIGATION_STEPS"),
    containmentConsiderations: extract("CONTAINMENT_CONSIDERATIONS"),
    missingEvidence: extract("MISSING_EVIDENCE"),
  };
}

function validateSections(sections: ExplanationSections): boolean {
  // At least 3 non-trivial sections must be populated to accept the response
  const filled = Object.values(sections).filter(
    (v) => v && v.length > 30 && v !== "Not available in this explanation."
  );
  return filled.length >= 3;
}

