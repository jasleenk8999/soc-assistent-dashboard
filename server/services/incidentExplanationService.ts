/**
 * Incident Explanation Service (Phase 5)
 *
 * Generates structured, evidence-grounded AI explanations for security alerts.
 * Provider is configurable via environment variables:
 *   AI_PROVIDER = "openai" | "google" | "fallback"
 *   AI_API_KEY  = (provider API key)
 *   AI_MODEL    = specific model (e.g. "gpt-4o-mini", "gemini-1.5-flash")
 *
 * Security controls:
 *  - Fixed system instruction; logs are delimited as EVIDENCE not instructions
 *  - API key stays server-side only
 *  - No commands, URLs, or infrastructure access granted to AI
 *  - AI output is parsed into named sections; malformed output falls back gracefully
 *  - Input size limited to prevent prompt stuffing
 *  - Prompt-injection: evidence sections are enclosed in XML-style delimiters
 *
 * When no API key is configured, a deterministic evidence-based fallback is returned
 * with a clear FALLBACK_DETERMINISTIC label.
 */

import type { NormalizedLog } from "./logNormalizer";

// Maximum raw-log characters per log record sent to AI (prevent prompt stuffing)
const MAX_RAW_LOG_CHARS = 1500;
// Maximum number of logs to include in AI prompt
const MAX_LOGS_IN_PROMPT = 8;
// AI request timeout in ms
const AI_REQUEST_TIMEOUT_MS = parseInt(process.env.AI_REQUEST_TIMEOUT_MS || "30000", 10);

export interface ExplanationSections {
  executiveSummary: string;
  whyItTriggered: string;
  evidenceNarrative: string;
  mitreContext: string;
  potentialImpact: string;
  confidenceAndUncertainty: string;
  investigationSteps: string;
  containmentConsiderations: string;
  missingEvidence: string;
}

export interface ExplanationResult {
  sections: ExplanationSections;
  provider: string;
  model: string | null;
  status: "completed" | "failed";
  errorMessage?: string;
}

export interface AlertContext {
  id: number;
  ruleId?: string | null;
  ruleName?: string | null;
  severity: string;
  title: string;
  source: string;
  destination?: string | null;
  tactic: string;
  technique?: string | null;
  confidence: string;
  description?: string | null;
  evidence?: any;
  suggestedNextSteps?: string | null;
  dedupKey?: string | null;
  threatIntel?: any[];
  createdAt: Date;
}

export interface LogContext {
  id: number;
  timestamp: Date;
  sourceType: string;
  sourceIp?: string | null;
  destinationIp?: string | null;
  sourcePort?: number | null;
  destinationPort?: number | null;
  username?: string | null;
  eventId?: string | null;
  eventCategory?: string | null;
  logLevel: string;
  rawLog: string;
  parsedFields?: any;
  isThreat: boolean;
  threatReason?: string | null;
}

