export function buildDeterministicFallback(alert: AlertContext, logs: LogContext[]): ExplanationSections {
  const logSummary =
    logs.length > 0
      ? `${logs.length} log record(s) linked (IDs: ${logs.map((l) => l.id).join(", ")}).`
      : "No log records are directly linked to this alert.";

  const ips = Array.from(new Set(logs.map((l) => l.sourceIp).filter(Boolean)));
  const users = Array.from(new Set(logs.map((l) => l.username).filter(Boolean)));
  const ipText = ips.length > 0 ? `Source IPs observed: ${ips.join(", ")}.` : "No source IPs in linked logs.";
  const userText = users.length > 0 ? `Users involved: ${users.join(", ")}.` : "";

  const evidenceKeys = Object.keys(
    typeof alert.evidence === "object" && alert.evidence ? alert.evidence : {}
  ).join(", ");

  const intelNotes =
    Array.isArray(alert.threatIntel) && alert.threatIntel.length > 0
      ? "\nThreat Intelligence Context (Observational Feeds):\n" +
        alert.threatIntel
          .map((ti: any) => {
            const feedSummary = Array.isArray(ti.feedVerdicts)
              ? ti.feedVerdicts
                  .filter((f: any) => f.status === "success")
                  .map(
                    (f: any) =>
                      `${f.provider}: ${f.verdict} (Detections: ${f.detectionsCount ?? 0}/${f.totalEngines ?? 0}, Score: ${f.reputationScore ?? 0}/100) [Retrieved: ${f.retrievedAt ? new Date(f.retrievedAt).toISOString().slice(0, 10) : "cached"}]`
                  )
                  .join("; ")
              : "Cached record";
            return `• Indicator ${ti.indicator} (${ti.indicatorType}): Verdict=${ti.verdict}, RepScore=${ti.reputationScore}/100. Provider Feeds: ${feedSummary || "Database cache"}.`;
          })
          .join("\n") +
        "\nNote: External threat intelligence provides reputation context and does not independently prove an attack without local corroborating log telemetry."
      : "";

  return {
    executiveSummary:
      `[FALLBACK_DETERMINISTIC — AI provider not configured] ` +
      `Alert "${alert.title}" (severity: ${alert.severity}) was generated by detection rule ${alert.ruleId ?? "unknown"} ` +
      `against source ${alert.source}. ${logSummary} Manual investigation is required.` +
      (alert.threatIntel && alert.threatIntel.some((t: any) => t.verdict === "Malicious")
        ? ` Note: Correlated threat intelligence flagged involved indicators as Malicious.`
        : ""),

    whyItTriggered:
      `Detection rule ${alert.ruleId ?? "N/A"} ("${alert.ruleName ?? alert.title}") matched telemetry from source ${alert.source}. ` +
      `The rule evaluated the ingested log and found a match against its signature or threshold condition. ` +
      `Confidence reported by the detection engine: ${alert.confidence}%.`,

    evidenceNarrative:
      `${logSummary} ${ipText} ${userText} ` +
      (evidenceKeys ? `Structured evidence fields: ${evidenceKeys}.` : "No additional structured evidence fields.") +
      intelNotes,

    mitreContext:
      `MITRE ATT&CK mapping stored with this alert: Tactic ${alert.tactic}` +
      (alert.technique ? `, Technique ${alert.technique}` : "") +
      `. This mapping was assigned by the detection engine at rule definition time. No AI verification has been performed.`,

    potentialImpact:
      `If this alert represents a genuine attack, potential consequences depend on ${alert.tactic} behavior. ` +
      `Severity is rated ${alert.severity}. The actual impact cannot be confirmed without further investigation of the endpoint, logs, and network traffic.`,

    confidenceAndUncertainty:
      `The detection confidence of ${alert.confidence}% reflects the rule-matching certainty of the deterministic engine. ` +
      `This fallback explanation was generated without an AI provider and contains no probabilistic AI assessment.` +
      (alert.threatIntel?.length
        ? ` Cross-referenced with ${alert.threatIntel.length} threat intelligence indicator(s).`
        : ""),

    investigationSteps:
      alert.suggestedNextSteps ||
      `1. Review the linked logs (${logs.map((l) => `#${l.id}`).join(", ") || "none"}) for corroborating indicators.\n` +
        `2. Query endpoint telemetry for source ${alert.source}.\n` +
        `3. Validate the MITRE mapping against observed behavior.\n` +
        `4. Escalate if additional indicators of compromise are found.`,

    containmentConsiderations:
      `Consider blocking source ${alert.source} at the network perimeter if malicious intent is confirmed. ` +
      `Containment actions should be reviewed by a Senior Analyst or Incident Commander before execution.`,

    missingEvidence:
      `To confirm or refute this alert: (1) endpoint telemetry from ${alert.source}, ` +
      `(2) full PCAP or session logs for the involved IPs, ` +
      `(3) authentication audit trail${users.length > 0 ? ` for user(s): ${users.join(", ")}` : ""}, ` +
      `(4) threat intelligence cross-reference for ${ips.join(", ") || alert.source}.`,
  };
}

